import type { RawMessage, RawWorkItem } from "./raw";

/**
 * A file on the message, referenced not linked: source download URLs are signed
 * and short-lived (Freshdesk's expire in minutes), and the file is already on
 * the same ticket a transcript is posted to.
 */
export interface CompactAttachment {
  name: string;
  size?: number;
  type?: string;
}

export interface CompactTurn {
  n: number;
  speaker: string;
  at: string;
  kind: "reply" | "internal_note" | "quoted";
  source_message?: string;
  text: string;
  attachments?: CompactAttachment[];
}

export interface CompactStats {
  source_messages: number;
  turns: number;
  raw_chars: number;
  compact_chars: number;
  dropped: {
    automated: number;
    auto_reply: number;
    exact_duplicate_blocks: number;
    near_duplicate_blocks: number;
    boilerplate_lines: number;
    prior_transcript: number;
  };
  /** Quoted messages older than the ticket - history that exists nowhere else. */
  recovered_earlier: number;
  /** Files referenced by name; never re-uploaded, never linked (URLs expire). */
  attachments: number;
}

export interface CompactedWorkItem {
  ticket: {
    external_id: string;
    title?: string;
    url?: string;
    opened?: string;
    updated?: string;
  };
  compaction: CompactStats;
  speakers: string[];
  turns: CompactTurn[];
  /** Source ids of transcripts a previous run posted, so they can be replaced. */
  prior_transcript_ids: string[];
}

export interface CompactOptions {
  /** A line repeated in at least this many blocks is treated as boilerplate. */
  boilerplateThreshold?: number;
  /** An angle-bracket URL repeated at least this often is a tracking link. */
  trackerThreshold?: number;
  /** 5-gram containment above which a block counts as a near-duplicate. */
  nearDuplicateRatio?: number;
  /** Keep automated reminders and out-of-office replies as turns. */
  keepAutomated?: boolean;
}

const MAIL_HEADER_LINE =
  /^\s*(De|From|Von|Da|Van|Enviado(\s+el)?|Sent|Gesendet(\s+am)?|Verzonden|Para|To|An|Aan|Cc|CC|CCO|Bcc|Asunto|Subject|Betreff|Onderwerp|Fecha|Date|Datum|Responder a|Reply-To|Importancia|Priority)\s*:/i;
const WROTE_VERBS =
  "escribió|escreveu|wrote|schrieb|schreef|a écrit|ha scritto|napisał\\(a\\)|napisał|написал\\(а\\)|написал|skrev";
/**
 * The "On 3 May 2024, Ana wrote:" line above a quoted message. `\b` is
 * ASCII-only, so the character before a Cyrillic verb is matched as "not a
 * letter" instead.
 */
const WROTE = new RegExp(
  `^\\s*(?:El|On|Am|Op|Le|Il|Em|W dniu|\\d)[^\\n]{0,200}?[^\\p{L}](?:${WROTE_VERBS})\\s*:?\\s*$`,
  "iu",
);
const WROTE_TAIL = new RegExp(`\\s*(?:${WROTE_VERBS})\\s*:?\\s*$`, "iu");
/** Quoting nested deeper than this is left as text. */
const MAX_QUOTE_DEPTH = 8;
/** Two header lines within this many lines start a quoted message. */
const HEADER_RUN_WINDOW = 6;
const HEADER_RUN_MIN = 2;
/** One level of plain-text quoting; the block below it is history, not new text. */
const QUOTED_LINE = /^\s*>/;
const FROM_LINE = /^\s*(De|From|Von|Da|Van)\s*:\s*(.+)$/i;
const WHEN_LINE =
  /^\s*(Enviado(\s+el)?|Sent|Gesendet(\s+am)?|Fecha|Date|Datum|Verzonden)\s*:\s*(.+)$/i;
const HORIZONTAL_RULE = /^[_\-\u2014=*·]{4,}$/;
/** Placeholder left where an image was, so a reader knows one existed. */
export const IMAGE_MARK = "[image]";

